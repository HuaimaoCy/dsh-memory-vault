import assert from 'node:assert/strict'
import {writeFileSync,mkdirSync} from 'node:fs'
import {resolve,join} from 'node:path'
export async function run(window,bridge){
  assert.match(bridge.databasePath,/focus-ui-test\.sqlite$/)
  const js=source=>window.webContents.executeJavaScript(source),pause=ms=>new Promise(done=>setTimeout(done,ms))
  const until=async expression=>{for(let n=0;n<240;n++){if(await js(expression))return;await pause(30)}throw new Error(`Focus UI timeout: ${expression}`)}
  const click=selector=>js(`document.querySelector(${JSON.stringify(selector)}).click()`)
  const api=(op,body={})=>js(`window.vault.notebook(${JSON.stringify(op)},${JSON.stringify(body)}).then(r=>{if(!r.ok)throw new Error(r.error);return r.result})`)
  const shot=async name=>{const i=process.argv.indexOf('--shots');if(i<0)return;await pause(280);const out=resolve(process.argv[i+1]);mkdirSync(out,{recursive:true});writeFileSync(join(out,name),(await window.webContents.capturePage()).toPNG())}
  await until(`!document.querySelector('#alaya-startup')`)
  const note=await api('save',{type:'note',title:'专注阅读',stem:'这是一篇专注模式测试笔记。\n\n正文可以阅读、批注与编辑。'})
  await click('#mode-switch')
  await until(`document.body.dataset.mode==='mistakebook'&&document.querySelector('[data-question-id]')`)
  const r=await js(`(()=>{const r=document.querySelector('[data-question-id]').getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)}})()`)
  window.webContents.sendInputEvent({type:'mouseDown',...r,button:'left',clickCount:1});window.webContents.sendInputEvent({type:'mouseUp',...r,button:'left',clickCount:1})
  await pause(80)
  assert.equal(await js(`document.querySelector('.mb-shell').classList.contains('detail-full')`),false,'单击只选择卡片')
  window.webContents.sendInputEvent({type:'mouseDown',...r,button:'left',clickCount:2});window.webContents.sendInputEvent({type:'mouseUp',...r,button:'left',clickCount:2})
  await until(`document.querySelector('.mb-shell.detail-full #mb-note-view')`)
  const facts=await js(`(()=>{const detail=document.querySelector('#mb-detail').getBoundingClientRect(),icons=[...document.querySelectorAll('.mb-focus-toolbar .icon')].map(e=>{const r=e.getBoundingClientRect();return {w:r.width,h:r.height,cy:r.y+r.height/2}});return {width:detail.width,hidden:getComputedStyle(document.querySelector('.mb-main')).display,icons,right:document.querySelectorAll('.mb-focus-actions button').length}})()`)
  assert.ok(Math.abs(facts.width-1440)<2);assert.equal(facts.hidden,'none');assert.equal(facts.right,3)
  assert.ok(facts.icons.every(i=>i.w===20&&i.h===20));assert.ok(Math.max(...facts.icons.map(i=>i.cy))-Math.min(...facts.icons.map(i=>i.cy))<1,JSON.stringify(facts))
  await shot('focus-reading.png')
  await click('#mb-note-ai')
  await until(`!document.querySelector('#mb-ai-side').hidden`)
  assert.ok(await js(`(()=>{const r=document.querySelector('#mb-ai-side').getBoundingClientRect();return r.left<20&&r.top>=0&&r.bottom<=innerHeight&&r.height>innerHeight*.8&&document.querySelector('.mb-focus-toolbar').getBoundingClientRect().top>=0})()`),'左侧 AI 必须完整显示，不能把阅读页推离视口')
  await shot('focus-ai-left.png')
  await click('#mb-ai-side [aria-label="收起 AI 助手"]')
  await click('#mb-annotate')
  await until(`document.querySelector('#mb-annotation-text')`)
  await js(`document.querySelector('#mb-annotation-text').value='已确认并保存的批注'`)
  await click('#mb-annotation-save')
  await until(`!document.querySelector('.mb-dialog[open]')&&document.querySelector('.mb-annotation')`)
  assert.equal((await api('read',{id:note.id})).annotations[0].text,'已确认并保存的批注')
  await click('#mb-edit');await until(`document.querySelector('[data-mb-field="title"]')`)
  await js(`(()=>{const e=document.querySelector('[data-mb-field="title"]');e.value='专注阅读已编辑';e.dispatchEvent(new Event('input',{bubbles:true}))})()`)
  await click('#mb-save')
  await until(`document.querySelector('.mb-reading-title')?.textContent==='专注阅读已编辑'`)
  await click('#mb-back')
  await until(`!document.querySelector('.mb-shell.detail-full')`)
  await click('#mb-ai-toggle');await until(`!document.querySelector('#mb-ai-side').hidden`)
  assert.ok(await js(`document.querySelector('#mb-ai-side').getBoundingClientRect().left<20`))
  await click('#mb-ai-side [aria-label="收起 AI 助手"]')
  await js('location.reload()')
  await until(`!document.querySelector('#alaya-startup')&&document.body.dataset.mode==='mistakebook'`)
  const saved=await api('read',{id:note.id});assert.equal(saved.title,'专注阅读已编辑');assert.equal(saved.annotations.length,1)
  console.log('Focus UI: real single/double click, full page, four aligned icons, left AI, persistent annotations/edit and return passed')
}
