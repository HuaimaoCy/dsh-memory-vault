import assert from 'node:assert/strict'
export async function run(window,bridge){
  assert.match(bridge.databasePath,/paper-ui-test\.sqlite$/)
  const js=source=>window.webContents.executeJavaScript(source)
  const pause=ms=>new Promise(done=>setTimeout(done,ms))
  const until=async expression=>{for(let n=0;n<240;n++){if(await js(expression))return;await pause(30)}throw new Error(`Paper UI timeout: ${expression}; ${await js(`document.querySelector('#mb-status')?.textContent`)}`)}
  const click=selector=>js(`document.querySelector(${JSON.stringify(selector)}).click()`)
  const api=(op,body={})=>js(`window.vault.notebook(${JSON.stringify(op)},${JSON.stringify(body)}).then(r=>{if(!r.ok)throw new Error(r.error);return r.result})`)
  await until(`!document.querySelector('#alaya-startup')`)
  const q1=await api('save',{type:'mistake',title:'试卷测试一',stem:'1 + 1 = ?'}),q2=await api('save',{type:'mistake',title:'试卷测试二',stem:'2 + 2 = ?'})
  await click('#mode-switch')
  await until(`document.body.dataset.mode==='mistakebook' && document.querySelectorAll('#mb-list [data-question-id]').length===2`)
  assert.equal(await js(`Boolean(document.querySelector('[data-mb-view="archived"],[data-mb-type="physics"],[data-mb-type="method"]'))`),false)
  assert.ok(await js(`document.querySelector('#mb-types #mb-open-canvas')`))
  const metrics=await js(`(()=>{const icons=[...document.querySelectorAll('.mb-bar .toolbar-actions > .icon-button .icon,.mb-bar #mb-new .icon')].filter(e=>e.getBoundingClientRect().width>0).map(e=>{const r=e.getBoundingClientRect();return {w:r.width,h:r.height,cy:r.y+r.height/2}});return {icons,search:document.querySelector('.mb-bar .search-wrap').offsetHeight,newSize:document.querySelector('#mb-new').offsetWidth}})()`)
  assert.ok(metrics.icons.every(i=>i.w===20&&i.h===20))
  assert.ok(Math.max(...metrics.icons.map(i=>i.cy))-Math.min(...metrics.icons.map(i=>i.cy))<1)
  assert.equal(metrics.search,44);assert.equal(metrics.newSize,42)
  await click('#mb-new')
  assert.equal(await js(`document.querySelector('#mb-create-menu').open`),true)
  assert.equal(await js(`document.querySelector('#mb-new').textContent.trim()`),'')
  assert.equal(await js(`document.querySelector('#mb-canvas-button').closest('details').id`),'mb-create-menu')
  await click('#mb-compile-paper')
  await until(`document.querySelector('#mb-paper-name')`)
  await js(`(()=>{const e=document.querySelector('#mb-paper-name');e.value='周测卷';e.dispatchEvent(new Event('input',{bubbles:true}))})()`)
  await click(`[data-paper-question="${q1.id}"]`)
  await click(`[data-paper-question="${q2.id}"]`)
  await click('#mb-paper-save')
  await until(`!document.querySelector('.mb-dialog[open]') && document.querySelectorAll('#mb-list [data-question-id]').length===1 && document.querySelectorAll('.mb-paper-question').length===2`)
  const paper=(await api('list')).records[0]
  assert.equal(paper.type,'paper');assert.equal(paper.questions.length,2)
  await click(`[data-open-paper-question="${q1.id}"]`)
  await until(`document.querySelector('#mb-back')`)
  await click('#mb-back')
  await until(`document.querySelector('.mb-paper-reader')`)
  await click('#mb-back')
  await click('[data-mb-view="due"]')
  await until(`document.querySelector('#mb-list [data-question-id]')`)
  await js(`(()=>{const card=document.querySelector('#mb-list [data-question-id]'),target=document.querySelector('[data-mb-view="mastered"]'),dataTransfer=new DataTransfer();card.dispatchEvent(new DragEvent('dragstart',{bubbles:true,dataTransfer}));target.dispatchEvent(new DragEvent('dragover',{bubbles:true,cancelable:true,dataTransfer}));target.dispatchEvent(new DragEvent('drop',{bubbles:true,cancelable:true,dataTransfer}))})()`)
  await until(`document.querySelectorAll('#mb-list [data-question-id]').length===0 && !document.querySelector('.mb-shell[aria-busy]')`)
  assert.equal((await api('read',{id:paper.id})).reviewState,'mastered')
  assert.equal((await api('read',{id:q1.id})).reviewState,'mastered')
  await click('[data-mb-view="mastered"]')
  await until(`document.querySelectorAll('#mb-list [data-question-id]').length===1`)
  await click('#mb-list [data-question-id]')
  await until(`document.querySelector('#mb-paper-dissolve')`)
  await click('#mb-paper-dissolve')
  await until(`document.querySelectorAll('#mb-list [data-question-id]').length===2`)
  assert.equal((await api('read',{id:q2.id})).stem,'2 + 2 = ?')
  await js('location.reload()')
  await until(`!document.querySelector('#alaya-startup') && document.body.dataset.mode==='mistakebook' && document.querySelectorAll('#mb-list [data-question-id]').length===2`)
  assert.equal((await api('read',{id:q1.id})).reviewState,'mastered')
  console.log('Paper UI: unified toolbar icons/new menu, compile one card, open/back, drag due to mastered, dissolve and reload persistence passed')
}
