import assert from 'node:assert/strict'
import {mkdirSync,writeFileSync} from 'node:fs'
import {resolve,join} from 'node:path'
import {ChromiumSession} from './preview-cdp.mjs'
import {createPreviewServer} from './preview-app.mjs'

const root=resolve(import.meta.dirname,'..'),index=process.argv.indexOf('--out')
const out=resolve(index<0?join(root,'test-tmp/preview/workspace-ui'):process.argv[index+1])
mkdirSync(out,{recursive:true})
const server=createPreviewServer()
await new Promise(done=>server.listen(0,'127.0.0.1',done))
const s=await ChromiumSession.launch({width:1440,height:940,profile:join(root,'test-tmp/work',`workspace-ui-${process.pid}`)})
const js=source=>s.evaluate(source),wait=source=>s.waitFor(source)
const click=selector=>js(`document.querySelector(${JSON.stringify(selector)}).focus();document.querySelector(${JSON.stringify(selector)}).click()`)
const pause=ms=>new Promise(done=>setTimeout(done,ms))
const results=[]
try{
  await s.goto(`http://127.0.0.1:${server.address().port}/?tier=full`)
  await wait(`!document.querySelector('#alaya-startup') && document.querySelector('#views .liquid-selection[data-glass-refraction="on"]')`)
  assert.equal(await js(`Boolean(document.querySelector('.foot,.mb-foot,#view-description,#saved-views,.views-head'))`),false)
  const rim=await js(`(()=>{const e=document.querySelector('.side .sidebar-rim'),r=e.getBoundingClientRect(),s=getComputedStyle(e);return {width:r.width,height:r.height,z:s.zIndex,border:s.borderTopWidth,shadow:s.boxShadow,reflection:s.backgroundImage.startsWith('url(')}})()`)
  assert.ok(rim.width>180&&rim.height>800&&Number(rim.z)>0&&rim.reflection&&rim.shadow==='none','侧栏需要独立的方向性曲面反光，不能用均匀光晕代替')
  const search=await js(`(()=>{const p=document.querySelector('.bar .search-wrap').getBoundingClientRect(),e=document.querySelector('.bar .search-wrap .icon'),r=e.getBoundingClientRect();return {opacity:getComputedStyle(e).opacity,dx:Math.abs(r.x+r.width/2-p.x-p.width/2),dy:Math.abs(r.y+r.height/2-p.y-p.height/2)}})()`)
  assert.equal(search.opacity,'1');assert.ok(search.dx<1&&search.dy<1)
  await click('#tree button')
  await wait(`document.querySelector('#tree .liquid-selection[data-glass-refraction="on"]') && document.querySelector('#tree button.on')`)
  assert.equal(await js(`getComputedStyle(document.querySelector('#tree button.on')).backgroundImage`),'none')
  await click('#workspace-settings')
  await wait(`document.querySelector('#modal[open] [data-sidebar-transparency]')`)
  assert.equal(await js(`document.querySelector('#modal .modal-status').textContent`),'')
  const setOpacity=async value=>{
    await js(`(()=>{const e=document.querySelector('[data-sidebar-transparency]');e.value='${value}';e.dispatchEvent(new Event('input',{bubbles:true}))})()`)
    assert.equal(await js(`Number(getComputedStyle(document.documentElement).getPropertyValue('--sidebar-opacity'))`),(100-value)/100)
  }
  await setOpacity(0);await setOpacity(100);await setOpacity(76)
  assert.equal(await js(`localStorage.getItem('alaya.sidebar.transparency')`),'76')
  await s.screenshot(join(out,'settings-appearance.png'))
  await click('#tab-layout')
  await wait(`document.querySelector('#settings-layout .ws-panel').getBoundingClientRect().width>200`)
  assert.equal(await js(`getComputedStyle(document.querySelector('#settings-layout .ws-panel')).position`),'static')
  await wait(`document.querySelector('.ws-seg .liquid-selection[data-glass-refraction="on"]')`)
  await s.screenshot(join(out,'settings-layout.png'))
  await click('#modal button[aria-label="关闭"]')
  await s.screenshot(join(out,'database.png'))
  results.push({mode:'memory',rim,search,settings:true,globalGroupLens:true,removedFooterAndViews:true})
  await js('location.reload()')
  await wait(`!document.querySelector('#alaya-startup') && window.alayaGlass`)
  assert.equal(await js(`Number(getComputedStyle(document.documentElement).getPropertyValue('--sidebar-opacity'))`),.24)
  await click('#mode-switch')
  await wait(`document.body.dataset.mode==='mistakebook' && document.querySelector('#mb-types button')`)
  assert.equal(await js(`Boolean(document.querySelector('[data-mb-view="archived"],[data-mb-type="physics"],[data-mb-type="method"]'))`),false)
  const icons=await js(`[...document.querySelectorAll('.mb-bar .toolbar-actions > .icon-button .icon,.mb-bar #mb-new .icon')].filter(e=>e.getBoundingClientRect().width>0).map(e=>{const r=e.getBoundingClientRect();return {w:r.width,h:r.height,cy:r.y+r.height/2}})`)
  assert.ok(icons.length>=4&&icons.every(i=>Math.abs(i.w-20)<.05&&Math.abs(i.h-20)<.05)&&Math.max(...icons.map(i=>i.cy))-Math.min(...icons.map(i=>i.cy))<1,JSON.stringify(icons))
  await click('#mb-new')
  assert.equal(await js(`document.querySelector('#mb-create-menu').open`),true)
  assert.ok(await js(`document.querySelector('#mb-create-menu #mb-canvas-button')&&document.querySelector('#mb-create-menu #mb-import')`))
  await click('#mb-new')
  await click('#mb-types [data-mb-type="note"]')
  await wait(`document.querySelector('#mb-types .liquid-selection[data-glass-refraction="on"]')`)
  await click('#mb-workspace-settings')
  await wait(`document.querySelector('.mb-dialog[open] [data-sidebar-transparency]')`)
  assert.equal(await js(`document.querySelector('[data-sidebar-transparency]').value`),'76')
  await click('.mb-dialog [data-tab="layout"]')
  assert.ok(await js(`document.querySelector('.mb-dialog .settings-embedded-layout .ws-panel').getBoundingClientRect().width>200`))
  await click('.mb-dialog [aria-label="关闭对话框"]')
  await click('[data-mb-view="all"]')
  await s.screenshot(join(out,'notebook.png'))
  await click('#mb-list [data-question-id]')
  await wait(`document.querySelector('.mb-shell.detail-full #mb-note-view')`)
  assert.ok(await js(`document.querySelector('.mb-focus-toolbar').getBoundingClientRect().top>=0`),'专注页工具栏不能移出屏幕')
  await s.screenshot(join(out,'focus-reading.png'))
  await click('#mb-note-ai')
  await wait(`!document.querySelector('#mb-ai-side').hidden`)
  assert.ok(await js(`(()=>{const r=document.querySelector('#mb-ai-side').getBoundingClientRect();return r.top>=0&&r.bottom<=innerHeight&&r.height>innerHeight*.8})()`))
  await s.screenshot(join(out,'focus-ai-left.png'))
  await click('#mb-ai-side [aria-label="收起 AI 助手"]')
  await click('#mb-back')
  await js(`window.__originalPreviewNotebook=window.vault.notebook;window.vault.notebook=(op,body)=>op==='read'?Promise.resolve({ok:true,result:null}):window.__originalPreviewNotebook(op,body)`)
  await click('#mb-list [data-question-id]')
  await wait(`!document.querySelector('.mb-shell[aria-busy]')`)
  assert.equal(await js(`document.querySelector('.mb-shell').classList.contains('detail-full')`),false,'读取失败应留在列表，不能白屏')
  await js(`window.vault.notebook=window.__originalPreviewNotebook;delete window.__originalPreviewNotebook`)
  await click('#mb-open-canvas')
  await wait(`document.querySelector('.mb-shell.canvas-on')`)
  assert.equal(await js(`document.querySelector('#mb-canvas-hint').hidden`),true)
  const canvas=await js(`(()=>{const r=document.querySelector('#mb-canvas').getBoundingClientRect(),p=document.querySelector('#mb-canvas-tools').getBoundingClientRect(),z=document.querySelector('#mb-canvas-zoom-controls').getBoundingClientRect();return {x:r.x,y:r.y,w:r.width,h:r.height,paletteX:p.x,paletteY:p.y,paletteWidth:p.width,paletteBottom:p.bottom,zoomRight:z.right,undoGrouped:Boolean(document.querySelector('#mb-canvas-tools #mb-canvas-undo'))}})()`)
  assert.ok(canvas.x<1&&canvas.y<1&&Math.abs(canvas.w-1440)<1&&Math.abs(canvas.h-940)<1)
  assert.ok(canvas.undoGrouped&&Math.abs(canvas.paletteX+canvas.paletteWidth/2-720)<1&&canvas.paletteBottom<940&&canvas.paletteY>800)
  await click('#mb-canvas-text')
  await wait(`document.querySelectorAll('.mb-canvas-card').length===1`)
  await click('#mb-canvas-undo')
  await wait(`document.querySelectorAll('.mb-canvas-card').length===0`)
  await click('#mb-canvas-redo')
  await wait(`document.querySelectorAll('.mb-canvas-card').length===1`)
  await s.screenshot(join(out,'canvas.png'))
  await click('#mb-canvas-back')
  await wait(`!document.querySelector('.mb-shell.canvas-on')`)
  results.push({mode:'mistakebook',sharedOpacity:true,settings:true,globalGroupLens:true,canvas,undoRedo:true})
  assert.deepEqual(s.exceptions,[])
  writeFileSync(join(out,'results.json'),JSON.stringify(results,null,2))
  console.log('Workspace UI: directional rim, opacity persistence, global selection, settings, icons/new menu, focus/left AI, white-screen recovery and fullscreen canvas/undo/redo passed')
}catch(error){await s.screenshot(join(out,'failure.png'));console.error(await js(`({status:document.querySelector('#status')?.textContent,mbStatus:document.querySelector('#mb-status')?.textContent,dialogs:document.querySelectorAll('dialog[open]').length})`));throw error}
finally{await s.close();server.close()}
